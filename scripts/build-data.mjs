// Builds the compact data modules the app ships with, from vendored upstream files.
//   data/psl/public_suffix_list.dat  -> app/data/psl-data.js
//   data/unicode/confusables.txt     -> app/data/confusables-data.js
// Run: node scripts/build-data.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { domainToASCII } from 'node:url';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

// ---------- Public Suffix List ----------
const psl = readFileSync(join(root, 'data/psl/public_suffix_list.dat'), 'utf8');
const version = (psl.match(/^\/\/ VERSION: (.+)$/m) || [])[1] || 'unknown';
const commit = (psl.match(/^\/\/ COMMIT: (.+)$/m) || [])[1] || 'unknown';
const icann = [];
const priv = [];
let section = null;
for (const raw of psl.split('\n')) {
  const line = raw.trim();
  if (line.includes('===BEGIN ICANN DOMAINS===')) section = icann;
  else if (line.includes('===BEGIN PRIVATE DOMAINS===')) section = priv;
  else if (line.includes('===END')) section = null;
  if (!line || line.startsWith('//') || !section) continue;
  const rule = line.split(/\s/)[0];
  // Convert each label to ASCII (punycode) so runtime matching works on URL-API hostnames.
  let prefix = '';
  let body = rule;
  if (body.startsWith('!')) { prefix = '!'; body = body.slice(1); }
  const labels = body.split('.').map((l) => (l === '*' ? '*' : domainToASCII(l) || l));
  section.push(prefix + labels.join('.'));
}
writeFileSync(
  join(root, 'app/data/psl-data.js'),
  `// Generated by scripts/build-data.mjs from the Public Suffix List (https://publicsuffix.org/),\n` +
    `// licensed under the Mozilla Public License 2.0 (see data/psl/LICENSE). Do not edit by hand.\n` +
    `export const PSL_VERSION = ${JSON.stringify(version)};\n` +
    `export const PSL_COMMIT = ${JSON.stringify(commit)};\n` +
    `export const PSL_ICANN = ${JSON.stringify(icann.join(' '))};\n` +
    `export const PSL_PRIVATE = ${JSON.stringify(priv.join(' '))};\n`
);
console.log(`PSL ${version}: ${icann.length} ICANN + ${priv.length} private rules`);

// ---------- Unicode confusables (subset) ----------
// Keep only single characters that are visually confusable with ASCII letters/digits and that
// can legally appear in an internationalized domain label (Latin-extended, Greek, Cyrillic,
// Armenian, Cherokee, fullwidth forms, etc.). Mathematical alphanumerics are dropped because IDNA
// maps them away before a domain is ever registered.
const conf = readFileSync(join(root, 'data/unicode/confusables.txt'), 'utf8');
const cver = (conf.match(/^# Version: (.+)$/m) || [])[1] || 'unknown';
const map = {};
for (const line of conf.split('\n')) {
  if (!line || line.startsWith('#')) continue;
  const [src, tgt] = line.split(';').map((s) => s.trim());
  if (!src || !tgt || src.includes(' ')) continue;
  const cp = parseInt(src, 16);
  const allowed =
    (cp >= 0x00c0 && cp <= 0x058f) || // Latin-1 sup .. Armenian
    (cp >= 0x13a0 && cp <= 0x13ff) || // Cherokee
    (cp >= 0x1d00 && cp <= 0x1eff) || // phonetic ext, Latin ext additional
    (cp >= 0xff01 && cp <= 0xff5e) || // fullwidth ASCII
    (cp >= 0x0400 && cp <= 0x052f); // Cyrillic (+supplement)
  if (!allowed) continue;
  const target = tgt.split(' ').map((h) => String.fromCodePoint(parseInt(h, 16))).join('').toLowerCase();
  if (!/^[a-z0-9]{1,2}$/.test(target)) continue;
  map[String.fromCodePoint(cp)] = target;
}
writeFileSync(
  join(root, 'app/data/confusables-data.js'),
  `// Generated by scripts/build-data.mjs from Unicode confusables.txt (UTS #39, version ${cver}),\n` +
    `// (c) Unicode, Inc., Unicode License v3 (see data/unicode/LICENSE.txt). Subset: characters that\n` +
    `// look like ASCII letters/digits and may appear in domain names. Do not edit by hand.\n` +
    `export const CONFUSABLES_VERSION = ${JSON.stringify(cver)};\n` +
    `export const CONFUSABLES = ${JSON.stringify(map)};\n`
);
console.log(`confusables ${cver}: ${Object.keys(map).length} characters`);
